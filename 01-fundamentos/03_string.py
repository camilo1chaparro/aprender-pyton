#Cadenas de texto en python

letra = 'c' #Esta es una cadena de texto de un solo caracter
print (letra) 
print (len(letra)) #len() retorna el tamaño (el número de elementos) de un objeto

texto = "Hola Mundo" #Esta es una cadena de texto de varios caracteres
print (texto)
print (len(texto)) 

#Concatencación de cadenas de texto

primer_nombre = 'Juan'
segundo_nombre = 'Camilo'
espacio = ' '
nombre_completo = primer_nombre + espacio + segundo_nombre
print (nombre_completo)

